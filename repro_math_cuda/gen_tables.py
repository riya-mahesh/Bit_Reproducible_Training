#!/usr/bin/env python3
# Generates repro_math_tables.h: the constants of repro_math.cuh, from 300-bit arithmetic.
# Usage: python3 gen_tables.py > repro_math_tables.h     (needs mpmath)
import math
import struct
from mpmath import mp, mpf, log, exp, floor, ldexp

mp.prec = 300


def rn24(v):
    """Nearest float32 to v (ties to even), for |v| in the normal range."""
    v = mpf(v)
    if v == 0:
        return mpf(0)
    m, e = mp.frexp(v)                    # v = m * 2^e, 0.5 <= |m| < 1
    q = ldexp(m, 24)
    n = int(floor(q))
    frac = q - n
    if frac > 0.5 or (frac == 0.5 and n % 2):
        n += 1
    return ldexp(mpf(n), e - 24)


def hexf(v):
    return float(v).hex().replace("0x1.", "0x1.") + "f" if v != 0 else "0.0f"


def lit(v):
    # Every value is a float32, so the double conversion is exact and %a round-trips.
    v = mpf(v)
    d = float(v)
    assert mpf(d) == v
    assert struct.unpack("f", struct.pack("f", d))[0] == d
    return (d.hex() + "f") if d != 0 else "0.0f"


def ff(v):
    hi = rn24(v)
    return hi, rn24(v - hi)


out = []
w = out.append
w("// Generated by gen_tables.py (300-bit arithmetic). Do not edit by hand.")
w("// Each entry is an exact float32, written in hex so every compiler reads the same bits.")
w("#pragma once")
w("")

# ---- exp: x = k * ln2/64 + r, k = 64 m + j ----
ln2 = log(2)
C = ln2 / 64
c1 = ldexp(floor(ldexp(C, 16)), -16)      # 10 significant bits: k * C1 is exact for |k| < 2^14
c2 = rn24(C - c1)
c3 = rn24(C - c1 - c2)
w("#define REPRO_EXP_INV_C   %s  /* 64/ln2 */" % lit(rn24(64 / ln2)))
w("#define REPRO_EXP_C1      %s" % lit(c1))
w("#define REPRO_EXP_C2      %s" % lit(c2))
w("#define REPRO_EXP_C3      %s" % lit(c3))
w("#define REPRO_EXP_P3      %s  /* 1/3! */" % lit(rn24(mpf(1) / 6)))
w("#define REPRO_EXP_P4      %s  /* 1/4! */" % lit(rn24(mpf(1) / 24)))
w("#define REPRO_EXP_P5      %s  /* 1/5! */" % lit(rn24(mpf(1) / 120)))
w("")

# Largest float32 below/above the thresholds where the correctly rounded exp is 0 or inf.
def next_float(v, up):
    d = float(v)
    b = struct.unpack("<I", struct.pack("<f", d))[0]
    if d > 0:
        b += 1 if up else -1
    else:
        b += -1 if up else 1
    return struct.unpack("<f", struct.pack("<I", b))[0]

over_point = ldexp(mpf(2) ** 24 * 2 - 1, 127 - 24)  # FLT_MAX + half ulp = (2 - 2^-24) * 2^127
x = rn24(log(over_point))
while exp(mpf(float(x))) < over_point:
    x = mpf(next_float(x, True))
while exp(mpf(next_float(x, False))) >= over_point:
    x = mpf(next_float(x, False))
w("#define REPRO_EXP_OVERFLOW %s  /* x >= this: exp rounds to +inf */" % lit(x))
und_point = mpf(2) ** -150                           # half the smallest subnormal
x = rn24(log(und_point))
while exp(mpf(float(x))) > und_point:
    x = mpf(next_float(x, False))
while exp(mpf(next_float(x, True))) <= und_point:
    x = mpf(next_float(x, True))
w("#define REPRO_EXP_UNDERFLOW %s  /* x <= this: exp rounds to +0 */" % lit(x))
w("")

w("#define REPRO_EXP_TABLE_DATA { /* 2^(j/64) as hi + lo */ \\")
for j in range(64):
    hi, lo = ff(mpf(2) ** (mpf(j) / 64))
    w("    {%s, %s}%s \\" % (lit(hi), lit(lo), "," if j < 63 else ""))
w("}")
w("")

# ---- log: x = 2^e z, z in [OFF, 2 OFF); log x = e ln2 + L_i + log1p(z c_i - 1) ----
OFF = 0x3f330000
N = 7
lnh = ldexp(floor(ldexp(ln2, 16)), -16)   # 16 significant bits: e * LNH is exact for |e| < 2^8
lnm = rn24(ln2 - lnh)
lnl = rn24(ln2 - lnh - lnm)
third = rn24(mpf(1) / 3)
w("#define REPRO_LOG_OFF     0x%08xu" % OFF)
w("#define REPRO_LOG_N       %d" % N)
w("#define REPRO_LOG_LN2H    %s" % lit(lnh))
w("#define REPRO_LOG_LN2M    %s" % lit(lnm))
w("#define REPRO_LOG_LN2L    %s" % lit(lnl))
w("#define REPRO_LOG_THIRD   %s" % lit(third))
w("#define REPRO_LOG_THIRDL  %s" % lit(rn24(mpf(1) / 3 - third)))
for n in range(4, 8):
    w("#define REPRO_LOG_P%d      %s  /* 1/%d */" % (n, lit(rn24(mpf(1) / n)), n))
w("")


def from_bits(b):
    return mpf(struct.unpack("<f", struct.pack("<I", b))[0])


w("#define REPRO_LOG_TABLE_DATA { /* c_i ~ 1/z, then -log(c_i) as hi + lo */ \\")
one_index = (0x3f800000 - OFF) >> (23 - N)
assert ((0x3f800000 - OFF) & ((1 << (23 - N)) - 1)) == 0
for i in range(1 << N):
    a = from_bits(OFF + (i << (23 - N)))
    b = from_bits(OFF + ((i + 1) << (23 - N)))
    # The two intervals touching z = 1 use c = 1 exactly: no table term, no cancellation.
    c = mpf(1) if i in (one_index - 1, one_index) else rn24(2 / (a + b))
    hi, lo = ff(-log(c)) if c != 1 else (mpf(0), mpf(0))
    w("    {%s, %s, %s}%s \\" % (lit(c), lit(hi), lit(lo), "," if i < (1 << N) - 1 else ""))
w("}")
print("\n".join(out))
